"""
Stage 2: Playwright Link Verifier
Reads results.json generated by check_links.py and uses a real headless browser
to verify broken, error, warning, and unknown responses. Protected responses are not treated as confirmed working or dead.
This records WAF challenges as protected/inconclusive and avoids false positive dead links.
"""

import os
import json
from datetime import datetime, timezone
from playwright.sync_api import sync_playwright
from link_health import classify_playwright_result, looks_like_parked_domain, looks_like_waf_challenge
from safe_urls import UnsafeURL, safe_browser_route, validate_public_http_url

def verify_with_playwright(browser, url):
    """Check the final browser response without attempting to bypass access controls."""
    context = None
    page = None
    last_response = [None]
    try:
        validate_public_http_url(url)
        context = browser.new_context(
            viewport={'width': 1280, 'height': 720},
            user_agent='Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'
        )
        page = context.new_page()

        page.route("**/*", safe_browser_route)

        def handle_response(response):
            if response.frame == page.main_frame and response.request.resource_type == "document":
                last_response[0] = response

        page.on("response", handle_response)
        response = page.goto(url, wait_until='domcontentloaded', timeout=12000)
        final_response = last_response[0] if last_response[0] else response
        status = final_response.status if final_response else None

        title = page.title().lower()
        try:
            content = page.content().lower()
        except Exception:
            content = ""

        if looks_like_parked_domain(title + " " + content):
            return False, status or 404, "Playwright: Parked domain or suspended hosting detected"

        if looks_like_waf_challenge(title + " " + content):
            return False, status if status and status >= 400 else 403, "Playwright: WAF challenge detected; endpoint availability is not confirmed"

        cf_down_indicators = (
            'web server is down', 'connection timed out', 'origin error', 'host error',
            'error 521', 'error 522', 'error 523', 'error 524', 'error 525', 'error 526'
        )
        if any(indicator in title or indicator in content for indicator in cf_down_indicators):
            return False, status, "Playwright: Temporary Cloudflare server outage"

        if status is not None and 200 <= status < 400:
            return True, status, "Playwright: Verified HTTP response"

        return False, status, f"Playwright: Final document HTTP {status if status is not None else 'unknown'}"

    except Exception as error:
        clean_error = str(error).replace('\\n', ' ; ')
        return False, None, f"Playwright Exception: {type(error).__name__}: {clean_error}"
    finally:
        if page:
            try:
                page.close()
            except Exception:
                pass
        if context:
            try:
                context.close()
            except Exception:
                pass


def save_reports(results, total_apis_count):
    script_dir = os.path.dirname(os.path.abspath(__file__))
    
    # 1. Save main report
    report_path = os.path.join(script_dir, 'link_check_report.txt')
    now = datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')
    
    with open(report_path, 'w', encoding='utf-8') as f:
        f.write("LINK CHECK REPORT (Hybrid Verified)\n")
        f.write("=" * 80 + "\n\n")
        f.write(f"Date: {now}\n")
        f.write(f"Total: {total_apis_count}\n")
        f.write(f"Working: {len(results['working'])}\n")
        f.write(f"Protected: {len(results['protected'])}\n")
        f.write(f"Warnings: {len(results['warning'])}\n")
        f.write(f"Errors: {len(results['error'])}\n")
        f.write(f"Broken: {len(results['broken'])}\n")
        f.write(f"Unknown: {len(results['unknown'])}\n\n")

        if results['broken']:
            f.write("BROKEN APIS:\n")
            f.write("-" * 80 + "\n")
            for r in sorted(results['broken'], key=lambda x: x['name']):
                f.write(f"\n{r['name']} ({r['category']})\n  -> URL: {r['url']}\n  -> Note: {r['note']}\n")

        if results['error']:
            f.write("\nERROR APIS:\n")
            f.write("-" * 80 + "\n")
            for r in sorted(results['error'], key=lambda x: x['name']):
                f.write(f"\n{r['name']} ({r['category']})\n  -> URL: {r['url']}\n  -> Note: {r['note']}\n")

        if results['unknown']:
            f.write("\nUNKNOWN APIS:\n")
            f.write("-" * 80 + "\n")
            for r in sorted(results['unknown'], key=lambda x: x['name']):
                f.write(f"\n{r['name']} ({r['category']})\n  -> URL: {r['url']}\n  -> Note: {r['note']}\n")

        if results['warning']:
            f.write("\nWARNING APIS:\n")
            f.write("-" * 80 + "\n")
            for r in sorted(results['warning'], key=lambda x: x['name']):
                f.write(f"\n{r['name']} ({r['category']})\n  -> URL: {r['url']}\n  -> Note: {r['note']}\n")
                
    # 2. Save broken URLs list (URL | Name (Category) - Reason)
    broken_list_path = os.path.join(script_dir, 'broken_urls.txt')
    with open(broken_list_path, 'w', encoding='utf-8') as f:
        for r in sorted(results['broken'], key=lambda x: x['url']):
            f.write(f"{r['url']} | {r['name']} ({r['category']}) - {r['note']}\n")

    # 3. Save error URLs list
    error_list_path = os.path.join(script_dir, 'error_urls.txt')
    with open(error_list_path, 'w', encoding='utf-8') as f:
        for r in sorted(results['error'], key=lambda x: x['url']):
            f.write(f"{r['url']} | HTTP {r['status']} | {r['name']} ({r['category']}) - {r['note']}\n")

    # 4. Save warning URLs list
    warning_list_path = os.path.join(script_dir, 'warning_urls.txt')
    with open(warning_list_path, 'w', encoding='utf-8') as f:
        for r in sorted(results['warning'], key=lambda x: x['url']):
            status_str = f"HTTP {r['status']}" if r['status'] else "N/A"
            f.write(f"{r['url']} | {status_str} | {r['name']} ({r['category']}) - {r['note']}\n")

    # 5. Save unknown URLs list
    unknown_list_path = os.path.join(script_dir, 'unknown_urls.txt')
    with open(unknown_list_path, 'w', encoding='utf-8') as f:
        for r in sorted(results['unknown'], key=lambda x: x['url']):
            status_str = f"HTTP {r['status']}" if r['status'] else "N/A"
            f.write(f"{r['url']} | {status_str} | {r['name']} ({r['category']}) - {r['note']}\n")

    # 6. Save protected URLs list
    protected_list_path = os.path.join(script_dir, 'protected_urls.txt')
    with open(protected_list_path, 'w', encoding='utf-8') as f:
        for r in sorted(results['protected'], key=lambda x: x['url']):
            status_str = f"HTTP {r['status']}" if r['status'] else "N/A"
            f.write(f"{r['url']} | {status_str} | {r['name']} ({r['category']}) - {r['note']}\n")


    # Persist the final Stage 2 classifications so CI consumes structured data,
    # not counts scraped from the human-readable report.
    results_json_path = os.path.join(script_dir, 'results.json')
    with open(results_json_path, 'w', encoding='utf-8') as handle:
        json.dump(results, handle, indent=2)


def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    results_path = os.path.join(script_dir, 'results.json')
    
    if not os.path.exists(results_path):
        print("No results.json found. Please run check_links.py first.")
        return 1
        
    with open(results_path, 'r', encoding='utf-8') as f:
        results = json.load(f)
        
    total_apis_count = sum(len(cat) for cat in results.values())
    
    # Stage 2 retries broken, server-error, timeout, and unknown responses in a browser.
    # Protected (401/403/418/429) responses remain inconclusive and are not bypassed.
    to_verify = []
    for state in ['broken', 'error', 'warning', 'unknown']:
        to_verify.extend(results[state])
        
    if not to_verify:
        print("No APIs need Playwright verification.")
        return 0
        
    print(f"Playwright Verification: checking {len(to_verify)} APIs...")
    
    # Process the queue reusing browser instance and caching checks per URL
    url_cache = {}
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True)
        for item in to_verify:
            url = item['url']
            old_state = item['state']
            name = item.get('name', '')
            category = item.get('category', '')
            
            print(f"Verifying [{old_state}] API {name} ({category}): {url}")
            
            if url in url_cache:
                is_working, new_status, note = url_cache[url]
                print(f"  -> [Cached] is_working={is_working}, status={new_status}, note={note}")
            else:
                is_working, new_status, note = verify_with_playwright(browser, url)
                url_cache[url] = (is_working, new_status, note)
            
            if is_working:
                print(f"  -> Success! Was {old_state}, now working.")
                # Remove from old category matching name and url
                results[old_state] = [i for i in results[old_state] if not (i['url'] == url and i.get('name') == name)]
                # Add to working (or protected if it's a Cloudflare challenge but verified)
                target_state = 'working' if 'Cloudflare Challenge' not in note else 'protected'
                results[target_state].append({
                    'name': name,
                    'category': category,
                    'url': url,
                    'status': new_status,
                    'state': target_state,
                    'note': note
                })
            else:
                print(f"  -> Still failing: {note}")
                # Remove from old category matching name and url
                results[old_state] = [i for i in results[old_state] if not (i['url'] == url and i.get('name') == name)]
                
                # Decide target category based on error
                target_state = classify_playwright_result(new_status, note)

                results[target_state].append({
                    'name': name,
                    'category': category,
                    'url': url,
                    'status': new_status,
                    'state': target_state,
                    'note': f"Stage 1: {item['note']} | Stage 2: {note}"
                })
        browser.close()
 
    print("\nVerification complete. Regenerating reports...")
    save_reports(results, total_apis_count)
    print("Hybrid reports successfully generated.")
    return 0
    
if __name__ == "__main__":
    exit(main())
